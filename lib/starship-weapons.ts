export function getWeaponsBySize(size: string): StarshipWeapon[] {
  const norm = size.toLowerCase()
  if (norm === 'huge' || norm === 'gargantuan') {
    return STARSHIP_WEAPONS.filter(w => w.sizeCategory === 'Huge-Gargantuan')
  }
  return STARSHIP_WEAPONS.filter(w => w.sizeCategory === 'Tiny-Large')
}

export function getAmmoForLauncher(launcherName: string): StarshipAmmunition[] {
  const norm = launcherName.toLowerCase()
  if (norm.includes('rocket') || norm.includes('cluster')) {
    return STARSHIP_AMMUNITION.filter(a => a.launcherFamily === 'Cluster pod')
  }
  if (norm.includes('missile')) {
    return STARSHIP_AMMUNITION.filter(a => a.launcherFamily === 'Missile launcher')
  }
  if (norm.includes('torpedo')) {
    return STARSHIP_AMMUNITION.filter(a => a.launcherFamily === 'Torpedo launcher')
  }
  if (norm.includes('bomb') || norm.includes('mine') || norm.includes('layer') || norm.includes('deployer')) {
    return STARSHIP_AMMUNITION.filter(a => a.launcherFamily === 'Quaternary Ammunition')
  }
  return []
}